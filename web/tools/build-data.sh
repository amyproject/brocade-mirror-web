#!/bin/sh
# Wraps the shared content file (../Baduanjin/Resources/moves.json) into web/data.js
# so index.html works from file:// (where fetch() of local JSON is blocked).
# Re-run whenever moves.json changes:   sh web/tools/build-data.sh
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="$HERE/../../Baduanjin/Resources/moves.json"
OUT="$HERE/../data.js"
# Validate JSON first so a broken edit fails loudly instead of producing a broken page.
if command -v python3 >/dev/null 2>&1; then
  python3 -c "import json,sys; json.load(open(sys.argv[1], encoding='utf-8'))" "$SRC"
fi
{
  printf '/* GENERATED by web/tools/build-data.sh from Baduanjin/Resources/moves.json. Do not edit by hand. */\n'
  printf 'window.BDJ = '
  cat "$SRC"
  printf ';\n'
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
