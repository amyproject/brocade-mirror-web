#!/usr/bin/env python3
"""English voiceover for the moves, generated with Deepgram Aura-2 TTS (Brocade Mirror).

    python3 web/tools/voice_content.py          # writes web/content/voice/en/*.mp3 + web/data-voice.js,
                                                # and copies them to Baduanjin/Resources/Voice + voice.json (iOS)
    python3 web/tools/voice_content.py --force  # regenerate every clip

Per move: m<N>-intro (explains the move: name, purpose, benefits, breathing), m<N>-name (short,
announced at each chapter of the full routine) and m<N>-s<K> (one per step, starting with the breath).
Text comes from Baduanjin/Resources/moves.json, so rerun after editing it. Existing clips are kept
unless their text changed. Deepgram has no Chinese voice; the app speaks Chinese with the system voice.
Key: $DEEPGRAM_API_KEY or ~/.config/brocade-mirror/deepgram.key (never inside baduanjin_app/).
"""
import hashlib, json, os, shutil, subprocess, sys, urllib.request
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.dirname(HERE)
OUT = os.path.join(WEB, 'content', 'voice', 'en')
MOVES = json.load(open(os.path.join(WEB, '..', 'Baduanjin', 'Resources', 'moves.json'), encoding='utf-8'))['moves']
VOICE = os.environ.get('DEEPGRAM_VOICE', 'aura-2-athena-en')  # calm, smooth
BREATH = {'in': 'Breathe in.', 'out': 'Breathe out.', 'hold': 'Hold.'}
BREATH_ZH = {'in': '吸气。', 'out': '呼气。', 'hold': '停。'}
NUM = ['', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight']


def key():
    k = os.environ.get('DEEPGRAM_API_KEY', '').strip()
    p = os.path.expanduser('~/.config/brocade-mirror/deepgram.key')
    if not k and os.path.exists(p):
        k = open(p).read().strip()
    if not k:
        sys.exit('No Deepgram key: set DEEPGRAM_API_KEY or write it to ' + p)
    return k


def scripts():
    """id -> {en, zh} text for every clip."""
    out = {}
    for m in MOVES:
        n = m['id']
        out['m%d-name' % n] = {'en': 'Move %s. %s.' % (NUM[n], m['nameEn']), 'zh': '第%s式，%s。' % (m['seal'], m['nameZh'])}
        out['m%d-intro' % n] = {
            'en': 'Move %s: %s. %s. %s Breathing: %s' % (NUM[n], m['nameEn'], m['subtitleEn'].rstrip('.'), m['benefitsEn'], m['breathingEn']),
            'zh': '第%s式，%s。%s。%s呼吸：%s' % (m['seal'], m['nameZh'], m['subtitleZh'].replace(' · ', '，'), m['benefitsZh'], m['breathingZh'])}
        for k, st in enumerate(m['steps'], 1):
            out['m%d-s%d' % (n, k)] = {'en': BREATH.get(st.get('breath'), '') + ' ' + st['en'],
                                       'zh': BREATH_ZH.get(st.get('breath'), '') + st['zh']}
    return out


def duration(path):
    r = subprocess.run(['afinfo', path], capture_output=True, text=True).stdout
    for line in r.splitlines():
        if 'estimated duration' in line:
            return round(float(line.split(':')[1].split()[0]), 2)
    return None


def tts(text, path, k):
    req = urllib.request.Request('https://api.deepgram.com/v1/speak?model=%s&encoding=mp3' % VOICE,
                                 data=json.dumps({'text': text}).encode(), method='POST',
                                 headers={'Authorization': 'Token ' + k, 'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    with open(path, 'wb') as f:
        f.write(data)


def main():
    force = '--force' in sys.argv
    os.makedirs(OUT, exist_ok=True)
    man_path = os.path.join(WEB, 'content', 'voice', 'manifest.json')
    old = json.load(open(man_path)) if os.path.exists(man_path) else {'clips': {}}
    S = scripts()
    k = key()
    todo = []
    for cid, t in S.items():
        h = hashlib.sha1((VOICE + t['en']).encode()).hexdigest()[:12]
        p = os.path.join(OUT, cid + '.mp3')
        if force or not os.path.exists(p) or old['clips'].get(cid, {}).get('h') != h:
            todo.append((cid, t['en'], p))
    with ThreadPoolExecutor(6) as ex:
        list(ex.map(lambda a: tts(a[1], a[2], k), todo))
    clips = {}
    for cid, t in S.items():
        p = os.path.join(OUT, cid + '.mp3')
        clips[cid] = {'h': hashlib.sha1((VOICE + t['en']).encode()).hexdigest()[:12], 'dur': duration(p), 'en': t['en'], 'zh': t['zh']}
    man = {'voice': VOICE, 'path': 'content/voice/en/', 'clips': clips}
    json.dump(man, open(man_path, 'w'), ensure_ascii=False, indent=1)
    with open(os.path.join(WEB, 'data-voice.js'), 'w', encoding='utf-8') as f:
        f.write('/* GENERATED by tools/voice_content.py, do not edit */\nwindow.BDJ_VOICE = ' + json.dumps(man, ensure_ascii=False) + ';\n')
    # iOS app: the Baduanjin/ folder is an Xcode synchronized group, so these ship in the bundle (flat names).
    ios = os.path.join(WEB, '..', 'Baduanjin', 'Resources', 'Voice')
    os.makedirs(ios, exist_ok=True)
    for cid in clips:
        shutil.copyfile(os.path.join(OUT, cid + '.mp3'), os.path.join(ios, cid + '.mp3'))
    with open(os.path.join(ios, '..', 'voice.json'), 'w', encoding='utf-8') as f:
        json.dump({'voice': VOICE, 'clips': {k: {'dur': c['dur'], 'en': c['en'], 'zh': c['zh']} for k, c in clips.items()}}, f, ensure_ascii=False)
    total = sum(c['dur'] or 0 for c in clips.values())
    print('voice %s: %d clips (%d new), %.0f s of audio -> content/voice/en/ + data-voice.js' % (VOICE, len(clips), len(todo), total))


if __name__ == '__main__':
    main()
